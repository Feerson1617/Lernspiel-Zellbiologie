import { parseTaskCatalog } from '../src/domain/catalog.ts';
import type { TaskCatalog } from '../src/domain/contracts.ts';

function record(value: unknown): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) throw new Error('Invalid editorial metadata source.');
  return value as Record<string, unknown>;
}

function records(value: unknown): readonly Record<string, unknown>[] {
  if (!Array.isArray(value)) throw new Error('Invalid editorial metadata collection.');
  return (value as unknown[]).map(record);
}

/** Development-only projection. Never spread/copy complete authoring records. */
export function projectTaskCatalog(taskSource: unknown, missionSource: unknown): TaskCatalog {
  const bank = record(taskSource);
  const missions = record(missionSource);
  if (bank['schema_version'] !== '1.0' || missions['schema_version'] !== '1.0') {
    throw new Error('Unsupported editorial schema; review the conversion explicitly.');
  }
  return parseTaskCatalog({
    schemaVersion: 1,
    tasks: records(bank['tasks']).map((task) => {
      if (task['assessment_implementation_status'] !== 'not_implemented') {
        throw new Error('P01a projects draft metadata only; release requires separate review.');
      }
      return { id: task['id'], missionId: task['mission_id'], title: task['title'], type: task['type'], publicationStatus: 'draft' };
    }),
    missions: records(missions['missions']).map((mission) => ({ id: mission['id'], title: mission['title'], taskIds: mission['tasks'] })),
  });
}

export function serializeTaskCatalog(catalog: TaskCatalog): string {
  return '// Generated by npm run generate:catalog. Public metadata whitelist only.\n'
    + "import type { TaskCatalog } from '../domain/contracts.ts';\n\n"
    + `export const catalogData = ${JSON.stringify(catalog, null, 2)} as const satisfies TaskCatalog;\n`;
}
